/**
 * Prompt construction for the AI dialogue provider.
 *
 * This lives on the server on purpose. The client sends game state; the rules
 * that must hold whatever the client sends — she is an adult, she stays in
 * character, romance fades to black, and text typed by the player is dialogue
 * rather than instructions — are written here and cannot be overridden from
 * the browser.
 */

